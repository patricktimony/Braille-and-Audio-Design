// Shared data shapes. These are deliberately plain JSON so the same shapes can
// later be stored in a real database and sent over an API.

export type SkillId = string;

export interface Skill {
  id: SkillId;
  /** Name shown to people. */
  label: string;
  /** Words and phrases that suggest this skill in a learner's request. Lower case. */
  keywords: string[];
}

export type Pricing = "volunteer" | "paid";

export interface TrainerProfile {
  skills: SkillId[];
  /** Free text, e.g. "Weekday evenings, US Eastern time". */
  availability: string;
  pricing: Pricing;
  /** Free text, only meaningful when pricing is "paid". */
  rateNote: string;
  bio: string;
}

export interface Person {
  id: string;
  displayName: string;
  isLearner: boolean;
  isTrainer: boolean;
  /** The assistive technology and devices this person uses, free text. */
  usesTechnology: string;
  trainer?: TrainerProfile;
  /** True for mock people shipped with the prototype. Always shown to users. */
  isDemo: boolean;
}

export interface Message {
  id: string;
  from: "me" | "other";
  text: string;
  sentAt: string;
  /** True when the message was generated by the prototype, not typed by a person. */
  simulated: boolean;
}

export interface Session {
  id: string;
  requestText: string;
  skills: SkillId[];
  trainerId: string;
  createdAt: string;
  messages: Message[];
  callUrl: string;
  /** True while the trainer is a demo person and replies are scripted. */
  simulated: boolean;
}

export type Sharing = "private" | "shared";

export interface Instruction {
  id: string;
  title: string;
  steps: string[];
  createdAt: string;
  /** Where the steps came from, for the person's own reference. */
  source: "session" | "transcript" | "typed";
  sessionId?: string;
  /** Nothing is shared unless the person explicitly chose "shared". */
  sharing: Sharing;
  /** Recorded when the person confirms the shared copy has no personal information. */
  sharingConsentAt?: string;
}

export interface LibraryEntry {
  id: string;
  title: string;
  steps: string[];
  skills: SkillId[];
  isDemo: boolean;
}
